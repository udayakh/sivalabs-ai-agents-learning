package dev.udaylabs.reviewbuddy.reviews.ai;

import dev.udaylabs.reviewbuddy.reviews.models.ReviewSubmittedEvent;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.modulith.events.ApplicationModuleListener;
import org.springframework.stereotype.Component;

/**
 * {@code @ApplicationModuleListener} = {@code @Async} + {@code @Transactional(REQUIRES_NEW)} +
 * {@code @TransactionalEventListener(AFTER_COMMIT)}. The event is also stored in the Spring
 * Modulith event publication registry (event_publication table), so if the LLM call fails or the
 * app crashes, the publication stays incomplete and can be retried (transactional outbox).
 */
@Component
class ReviewSummaryEventListener {

    private static final Logger log = LoggerFactory.getLogger(ReviewSummaryEventListener.class);

    private final ReviewSummaryService reviewSummaryService;

    ReviewSummaryEventListener(ReviewSummaryService reviewSummaryService) {
        this.reviewSummaryService = reviewSummaryService;
    }

    @ApplicationModuleListener
    void on(ReviewSubmittedEvent event) {
        log.info("Review {} submitted for product {} -> refreshing summary", event.reviewId(), event.productId());
        reviewSummaryService
                .regenerateSummary(event.productId())
                .ifPresent(s -> log.info("Summary for product {} generated by {}", s.productId(), s.generatedBy()));
    }
}
